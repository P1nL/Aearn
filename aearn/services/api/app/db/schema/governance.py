# Future candidates require explicit registration, independently of membership
# in an execution manifest. All three facts must be confirmed False for edits.
SCHEMA_CANDIDATE_FACTS: dict[str, CandidateEditFacts] = {}


def candidate_edit_blockers(facts: CandidateEditFacts) -> list[str]:
    """Report why in-place editing is denied; no mutation or DB observation."""
    return [
        f"{name}_{'confirmed' if value is True else 'unknown'}"
        for name, value in (
            ("installed_anywhere", facts.installed_anywhere),
            ("external_pin", facts.external_pin),
            ("freeze_commitment", facts.freeze_commitment),
        )
        if value is not False
    ]
